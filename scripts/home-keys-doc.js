#!/usr/bin/env node
// Prints the table of Home page keys (from shared/home-keymap.js and the registered views) or, with
// --write, puts it between the markers in docs/home-page.md. cli/test/home-keymap.test.js fails when the
// doc is out of date; run `node scripts/home-keys-doc.js --write` to fix it.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { homeViews } from '../dashboard/js/home-state.js';
import '../dashboard/js/home-placeholders.js'; // the five views, for their number keys
import { keyTable, keysMarkdown } from '../shared/home-keymap.js';

export const START = '<!-- keys:start (generated by scripts/home-keys-doc.js) -->';
export const END = '<!-- keys:end -->';
export const DOC = fileURLToPath(new URL('../docs/home-page.md', import.meta.url));

export function keysBlock() {
  return `${START}\n${keysMarkdown(keyTable({ views: homeViews() }))}\n${END}`;
}

/** The doc's text with its key table replaced (or null when the markers are missing). */
export function withKeys(text) {
  const a = text.indexOf(START);
  const b = text.indexOf(END);
  if (a < 0 || b < a) return null;
  return text.slice(0, a) + keysBlock() + text.slice(b + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--write')) {
    const next = withKeys(readFileSync(DOC, 'utf8'));
    if (next == null) { console.error('docs/home-page.md has no keys markers'); process.exit(1); }
    writeFileSync(DOC, next);
    console.log('docs/home-page.md updated');
  } else {
    console.log(keysBlock());
  }
}
